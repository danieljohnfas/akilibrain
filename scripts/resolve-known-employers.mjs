async function main() {
  console.log('Resolving known verified employer URLs in jobs table...');

  // Fast pre-filter: query distinct companies that actually need resolution
  const pendingRows = await sql`
    SELECT DISTINCT company_name
    FROM jobs
    WHERE is_active = true AND employer_url IS NULL
  `;
  const pendingNames = new Set(pendingRows.map(r => r.company_name));
  console.log(`Found ${pendingNames.size} distinct companies needing employer_url in DB.`);

  let totalUpdated = 0;
  for (const [companyName, url] of Object.entries(KNOWN_EMPLOYER_URLS)) {
    if (!pendingNames.has(companyName)) continue;

    const updated = await sql`
      UPDATE jobs
      SET employer_url = ${url}, is_aggregator_source = false, updated_at = NOW()
      WHERE is_active = true 
        AND employer_url IS NULL 
        AND company_name = ${companyName}
      RETURNING id
    `;
    if (updated.length > 0) {
      console.log(`[Resolved] ${companyName} -> ${url} (${updated.length} jobs updated)`);
      totalUpdated += updated.length;
    }
  }

  console.log(`\nSuccessfully resolved ${totalUpdated} jobs with direct verified employer URLs!`);
  await sql.end();
}

main().catch(async (e) => {
  console.error(e);
  await sql.end();
  process.exit(1);
});
